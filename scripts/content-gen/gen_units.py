lexicon = json.load(open(f'{REPO}/content/lexicon.json', encoding='utf8'))


def head(i):
    return HEAD_OVERRIDE.get(i) or STRONGS[i]['lemma']


def words(ref):
    toks = [t for t in V[ref] if not isinstance(t, str)]
    gl = GLOSS[ref]
    assert len(toks) == len(gl), (ref, len(toks), len(gl))
    out = []
    for t, (g, tr) in zip(toks, gl):
        lid = lemma_id(t)
        if lid not in lexicon:
            tl, gloss, pos = LEX[lid]
            lexicon[lid] = {'id': lid, 'lemma': head(lid), 'translit': tl, 'glossKo': gloss, 'posKo': pos}
        out.append({'surface': t['surface'], 'lemmaId': lid, 'translit': tr, 'glossKo': g, 'grammarKo': grammar(t['morph'])})
    return out


def ref_ko(ref):
    b, cv = ref.split(' ')
    c, v = cv.split('.')
    return f'{REF_KO[b]} {c}:{v}'


def find(ref, surface):
    for w in words(ref):
        if w['surface'] == surface: return w
    raise KeyError((ref, surface))


def line(ref, surfaces, ko):
    """A Hebrew line built from words of a verse (so every word has a checked lemma)."""
    ws = [find(ref, s) for s in surfaces]
    return {'he': ' '.join(w['surface'] for w in ws), 'translit': ' '.join(w['translit'] for w in ws), 'ko': ko,
            'lemmaIds': sorted({w['lemmaId'] for w in ws})}


def reading(lid, title, refs):
    return {'id': lid, 'type': 'reading', 'titleKo': title,
            'verses': [{'refKo': ref_ko(r), 'translationKo': TRANSLATION[r], 'words': words(r)} for r in refs]}


def choice_q(ref, surface, correct, wrong1, wrong2):
    w = find(ref, surface)
    return {'kind': 'choice', 'prompt': {'he': surface, 'ko': '이 단어의 뜻은?'}, 'choices': [correct, wrong1, wrong2],
            'answerIndex': 0, 'lemmaId': w['lemmaId']}


def order_q(ref, prompt, answer, distractor):
    ws = [find(ref, s) for s in answer]
    return {'kind': 'order', 'promptKo': prompt, 'tokens': [answer[-1], distractor, *answer[:-1]], 'answer': answer,
            'lemmaIds': sorted({w['lemmaId'] for w in ws})}


def opt(oid, ln, correct, nxt=None, fb=None):
    o = {'id': oid, 'line': ln, 'correct': correct}
    if nxt: o['next'] = nxt
    if fb: o['feedbackKo'] = fb
    return o


def blocks(prompt, ref, answer, distractors, nxt):
    ws = [find(ref, s) for s in answer]
    return {'mode': 'blocks', 'promptKo': prompt, 'tokens': [*reversed(answer), *distractors], 'accepted': [' '.join(answer)],
            'next': nxt, 'lemmaIds': sorted({w['lemmaId'] for w in ws})}


def roleplay(lid, title, setup, name_ko, name_he, avatar, nodes, start='intro'):
    ch = {'nameKo': name_ko, 'nameHe': name_he}
    if avatar: ch['avatarSrc'] = f'/illustrations/{avatar}.webp'
    return {'id': lid, 'type': 'roleplay', 'titleKo': title, 'setupKo': setup, 'character': ch, 'startNodeId': start,
            'nodes': {n['id']: n for n in nodes}}


