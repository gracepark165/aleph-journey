def pgn(s):
    return ' '.join(x for x in [PER.get(s[0:1], ''), GEN.get(s[1:2], ''), NUM.get(s[2:3], '')] if x)


def gn(s):
    return ' '.join(x for x in [GEN.get(s[0:1], ''), NUM.get(s[1:2], '')] if x)


def seg(code):
    k = code[0]
    if k == 'C': return '접속사 וְ'
    if k == 'R': return '전치사 + 정관사' if code[1:2] == 'd' else '전치사'
    if k == 'D': return '부사'
    if k == 'T': return PARTICLE.get(code[1:2], '불변화사')
    if k == 'S':
        if code[1:2] == 'p': return f'{pgn(code[2:])} 접미사'
        if code[1:2] == 'd': return '방향 접미사(~로)'
        return '강조 접미사'
    if k == 'P':
        if code[1:2] == 'p': return f'인칭대명사 {pgn(code[2:])}'
        if code[1:2] == 'd': return f'지시대명사 {gn(code[3:])}'
        return '대명사'
    if k == 'N':
        kind = {'c': '명사', 'g': '족속 명사', 'p': '고유명사'}.get(code[1:2], '명사')
        if code[1:2] == 'p': return kind
        st = STATE.get(code[4:5], '')
        return ' '.join(x for x in [kind, gn(code[2:4]), st] if x)
    if k == 'V':
        stem, t, rest = STEM.get(code[1:2], ''), code[2:3], code[3:]
        if t in 'rs':
            return ' '.join(x for x in [stem, VTYPE[t], gn(rest[0:2]), STATE.get(rest[2:3], '')] if x)
        if t in 'ac':
            return f'{stem} {VTYPE[t]}'
        return ' '.join(x for x in [stem, VTYPE.get(t, ''), pgn(rest)] if x)
    return code


def grammar(morph):
    segs = morph[1:].split('/')
    if segs == ['C']:
        return '접속사'  # a free-standing conjunction such as כִּי; 'וְ' only when prefixed
    return ' + '.join(seg(s) for s in segs)


def lemma_id(tok):
    if tok['main']: return tok['main']
    first = tok['lemma'].split('/')[0]
    return PSEUDO[first]


